import { chromium } from "playwright";
import { preview } from "vite";
const server = await preview({ root: ".", logLevel: "error", preview: { port: 4502, strictPort: true } });
const browser = await chromium.launch();
const ctx = await browser.newContext({ viewport: { width: 393, height: 851 }, isMobile: true, hasTouch: true });
const page = await ctx.newPage();
page.on("pageerror", (e) => console.log("ERR", e.message));
page.on("console", (m) => m.type() === "error" && console.log("CONSOLE", m.text()));
const cdp = await ctx.newCDPSession(page);
await page.addInitScript(() => { window.__long = []; new PerformanceObserver((l) => l.getEntries().forEach((e) => window.__long.push([Math.round(e.startTime), Math.round(e.duration)]))).observe({ type: "longtask", buffered: true }); });
await page.goto("http://localhost:4502/");
await page.click('[data-go="practice"]');
await cdp.send("Emulation.setCPUThrottlingRate", { rate: 4 });
await page.setInputFiles("#score-file", "/tmp/claude-0/canzona-like.musicxml");
await page.waitForFunction(() => performance.getEntriesByName("lento:open-score").length, null, { timeout: 180000 });
const log = async (label) => console.log(label, JSON.stringify(await page.evaluate(() => ({ relayouts: performance.getEntriesByName("lento:relayout-score").map((e) => Math.round(e.duration)), long: window.__long.splice(0).filter((x) => x[1] > 300) }))));
await log("opened");
await page.click("#play"); await page.waitForTimeout(3000);
await log("playing");
// rotate while playing
await page.setViewportSize({ width: 851, height: 393 }); await page.waitForTimeout(15000);
await log("rotated while playing");
await page.click("#focus-btn"); await page.waitForTimeout(1000);
await log("focus");
await page.setViewportSize({ width: 393, height: 851 }); await page.waitForTimeout(15000);
await log("rotated back");
const t = Date.now();
await page.click("#mini-show", { timeout: 60000 }); await page.click("#home-btn", { timeout: 60000 });
console.log("show+home clicks took", Date.now() - t, "ms; leave dialog open:", await page.evaluate(() => document.getElementById("leave-dialog").open));
process.exit(0);
